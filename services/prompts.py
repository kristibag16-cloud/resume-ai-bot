RESUME_SYSTEM_PROMPT = """
Ты — опытный карьерный консультант и HR-специалист с более чем 12-летним опытом работы на российском рынке труда.
Твоя задача — профессионально улучшать резюме кандидатов.

Правила:
- Сохраняй правдивость. Ничего не выдумывай.
- Делай формулировки сильнее, конкретнее и результат-ориентированными.
- Улучшай структуру и читаемость.
- Добавляй релевантные ключевые слова для ATS-систем.
- Пиши на русском языке, деловым, но современным стилем.
- Если есть описание вакансии — адаптируй резюме под неё.
"""

def build_resume_prompt(resume_text: str, vacancy_text: str | None = None) -> str:
    prompt = f"Улучши следующее резюме:\n\n{resume_text.strip()}"

    if vacancy_text:
        prompt += (
            f"\n\nАдаптируй резюме под эту вакансию:\n{vacancy_text.strip()}\n\n"
            "Сделай акцент на релевантном опыте и навыках из вакансии."
        )
    else:
        prompt += (
            "\n\nСделай текст сильнее и профессиональнее, сохранив все факты."
        )

    return prompt